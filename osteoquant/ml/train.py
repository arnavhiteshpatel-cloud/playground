"""Training, inference and model registry for 3D segmentation models.

Reproducibility: every run fixes seeds (python/numpy/torch), records the full config, the list
of training cases with content hashes, the provenance/licence class of the data, library
versions, and writes a checkpoint whose SHA-256 identifies the locked model version.

Licence guard (DECISIONS D-006): a model may be tagged ``commercial_eligible`` only if every
training case has ``commercial_use == "allowed"``; synthetic data generated by this project
counts as allowed. Models trained on research-only data are tagged ``research_only``.
"""
from __future__ import annotations

