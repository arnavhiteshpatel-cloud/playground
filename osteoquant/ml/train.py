from pathlib import Path

import numpy as np
import torch
import torch.nn.functional as F

from .unet import UNet3D, combined_loss, n_params

import os as _os
MODEL_DIR = Path(_os.environ["OQ_MODEL_DIR"]) if _os.environ.get("OQ_MODEL_DIR") else Path(__file__).resolve().parents[2] / "models"


@dataclass
class Case:
    case_id: str
    image: np.ndarray          # float32 (z,y,x), raw grey
    labels: np.ndarray | None  # uint8, 255 = ignore
    roi: np.ndarray | None
    spacing: tuple = (40.0, 40.0, 40.0)
    provenance: str = "synthetic"
    commercial_use: str = "allowed"
    meta: dict = field(default_factory=dict)


def seed_everything(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)


def normalize_image(img: np.ndarray, roi: np.ndarray | None = None, mode="percentile") -> np.ndarray:
    """Robust per-volume normalisation (cross-scanner harmonisation step)."""
    x = img.astype(np.float32)
    s = x[:: max(1, x.shape[0] // 32)]
    if mode == "percentile":
        lo, hi = np.percentile(s, [1, 99.8])
    elif mode == "zscore":
        m, sd = float(s.mean()), float(s.std()) + 1e-6
        return (x - m) / sd
    else:
        raise ValueError(mode)
    return (x - lo) / max(hi - lo, 1e-6)


def build_input(case: Case, cfg: dict) -> np.ndarray:
    chans = [normalize_image(case.image, mode=cfg.get("norm", "percentile"))]
    if cfg.get("roi_channel", False):
        r = case.roi if case.roi is not None else np.zeros(case.image.shape, bool)
        chans.append(r.astype(np.float32))
    if cfg.get("roi_distance_channel", False):
        from scipy import ndimage as ndi
        r = case.roi if case.roi is not None else np.zeros(case.image.shape, bool)
        d_in = ndi.distance_transform_edt(r, sampling=case.spacing)
        d_out = ndi.distance_transform_edt(~r, sampling=case.spacing)
        chans.append(np.tanh((d_in - d_out) / 500.0).astype(np.float32))
    return np.stack(chans).astype(np.float32)


# ----------------------------------------------------------------------------- augmentation
def augment(x: np.ndarray, y: np.ndarray, rng: np.random.Generator, cfg: dict):
    if cfg.get("aug_flip", True):
        for ax in (1, 2, 3):
            if rng.random() < 0.5:
                x = np.flip(x, ax)
                y = np.flip(y, ax - 1)
    if cfg.get("aug_rot90", True) and rng.random() < 0.5:
        k = int(rng.integers(1, 4))
        x = np.rot90(x, k, axes=(2, 3))
        y = np.rot90(y, k, axes=(1, 2))
    x = x.copy()
    if cfg.get("aug_intensity", True):
        a = rng.uniform(0.85, 1.15)
        b = rng.uniform(-0.08, 0.08)
        x[0] = x[0] * a + b
        if rng.random() < 0.3:
            g = rng.uniform(0.8, 1.25)
            x[0] = np.sign(x[0]) * np.abs(x[0]) ** g
    if cfg.get("aug_noise", True) and rng.random() < 0.5:
        x[0] += rng.normal(0, rng.uniform(0, 0.05), x[0].shape).astype(np.float32)
    if cfg.get("aug_blur", True) and rng.random() < 0.3:
        from scipy import ndimage as ndi
        x[0] = ndi.gaussian_filter(x[0], rng.uniform(0.3, 1.0))
    return np.ascontiguousarray(x), np.ascontiguousarray(y)


def sample_patch(x, y, roi, ps, rng, fg_prob=0.67):
    Z, Y, X = y.shape
    pz, py, pxx = [min(p, s) for p, s in zip(ps, (Z, Y, X))]
    if roi is not None and rng.random() < fg_prob and roi.any():
        pts = np.argwhere(roi[::2, ::2, ::2]) * 2
        c = pts[rng.integers(len(pts))]
        z0 = int(np.clip(c[0] - pz // 2, 0, Z - pz))
        y0 = int(np.clip(c[1] - py // 2, 0, Y - py))
        x0 = int(np.clip(c[2] - pxx // 2, 0, X - pxx))
    else:
        z0, y0, x0 = (int(rng.integers(0, Z - pz + 1)), int(rng.integers(0, Y - py + 1)),
                      int(rng.integers(0, X - pxx + 1)))
    sl = (slice(z0, z0 + pz), slice(y0, y0 + py), slice(x0, x0 + pxx))
    return x[(slice(None),) + sl], y[sl]


def _pad_to(x, y, ps):
    pads = [(0, max(0, p - s)) for p, s in zip(ps, y.shape)]
    if any(p[1] for p in pads):
        x = np.pad(x, [(0, 0)] + pads, mode="edge")
        y = np.pad(y, pads, constant_values=255)
    return x, y


# ----------------------------------------------------------------------------- training
def train_model(train_cases: list[Case], val_cases: list[Case], cfg: dict, name: str,
                log=print, init_from: str | None = None, sample_fn=None) -> dict:
    """Train a U-Net. ``sample_fn(rng) -> (x[C,Z,Y,X], y[Z,Y,X])`` optionally replaces patch sampling
    + augmentation (used for on-the-fly domain-randomised synthesis); it is recorded in the config
    by name (``cfg['sampler']``) for provenance."""
    if cfg.get("require_commercial_eligible") and any(c.commercial_use != "allowed" for c in train_cases):
        bad = sorted({c.case_id for c in train_cases if c.commercial_use != "allowed"})[:5]
        raise PermissionError(f"Commercial-release training refused: non-commercial or unresolved licence data {bad}")
    seed_everything(cfg.get("seed", 0))
    torch.set_num_threads(cfg.get("threads", 4))
    rng = np.random.default_rng(cfg.get("seed", 0))
    in_ch = 1 + int(cfg.get("roi_channel", False)) + int(cfg.get("roi_distance_channel", False))
    model = UNet3D(in_ch=in_ch, n_classes=cfg.get("n_classes", 4), base=cfg.get("base", 12),
                   levels=cfg.get("levels", 4), p_drop=cfg.get("dropout", 0.0))
    parent = None
    if init_from:
        ck = torch.load(init_from, map_location="cpu", weights_only=True)
        model.load_state_dict(ck["state_dict"])
        # provenance/licence of the parent model is inherited (review ARC-01): a fine-tuned model is never
        # more permissively licensed than its parent
        parent = {"name": ck.get("name"), "provenance": list(ck.get("provenance", [])),
                  "licence_tag": ck.get("licence_tag", "unknown"),
                  "sha256": hashlib.sha256(Path(init_from).read_bytes()).hexdigest()}
        if cfg.get("require_commercial_eligible") and parent["licence_tag"] != "commercial_eligible":
            raise PermissionError(f"Commercial-release training refused: parent model licence {parent['licence_tag']}")
    opt = torch.optim.AdamW(model.parameters(), lr=cfg.get("lr", 3e-3), weight_decay=1e-4)
    iters = cfg.get("iters", 1000)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, max_lr=cfg.get("lr", 3e-3), total_steps=iters,
                                                pct_start=0.1)
    ps = tuple(cfg.get("patch", (48, 48, 48)))
    bs = cfg.get("batch", 4)
    prepped = [(build_input(c, cfg), c.labels.astype(np.int64), c.roi) for c in train_cases]
    hist = []
    t0 = time.time()
    model.train()
    for it in range(iters):
        xb, yb = [], []
        for _ in range(bs):
            if sample_fn is not None and (not prepped or rng.random() < cfg.get("synth_prob", 1.0)):
                xp, yp = sample_fn(rng)
                xp, yp = _pad_to(xp.astype(np.float32), yp.astype(np.int64), ps)
            else:
                x, y, roi = prepped[rng.integers(len(prepped))]
                xp, yp = sample_patch(x, y, roi, ps, rng, cfg.get("fg_prob", 0.67))
                xp, yp = augment(xp, yp, rng, cfg)
                xp, yp = _pad_to(xp, yp, ps)
            xb.append(xp)
            yb.append(yp)
        xb = torch.from_numpy(np.stack(xb))
        yb = torch.from_numpy(np.stack(yb))
        logits = model(xb)
        loss = combined_loss(logits, yb, cfg.get("n_classes", 4), cfg.get("loss", {}))
        opt.zero_grad()
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 12.0)
        opt.step()
        sched.step()
        if (it + 1) % cfg.get("log_every", 100) == 0 or it == iters - 1:
            rec = {"iter": it + 1, "loss": float(loss), "sec": round(time.time() - t0, 1)}
            if val_cases and ((it + 1) % cfg.get("val_every", 500) == 0 or it == iters - 1):
                rec["val_mean_dice"] = evaluate_quick(model, val_cases, cfg)
                model.train()
            hist.append(rec)
            log(json.dumps(rec))
    sampler_manifest = getattr(sample_fn, "manifest", None) if sample_fn is not None else None
    return save_model(model, cfg, name, train_cases, hist, time.time() - t0, parent=parent,
                      sampler_manifest=sampler_manifest)


def evaluate_quick(model, cases, cfg) -> float:
    from ..segment.metrics import multiclass_metrics
    ds = []
    for c in cases:
        prob = predict_proba(model, c, cfg, tta=False)
        pred = prob.argmax(0).astype(np.uint8)
        r = multiclass_metrics(pred, c.labels, spacing=c.spacing, mask=c.roi if cfg.get("eval_in_roi") else None,
                               distances=False)
        ds.append(r["mean_dice"])
    return float(np.mean(ds))


def save_model(model, cfg, name, train_cases, hist, seconds, parent: dict | None = None,
               sampler_manifest: list | None = None) -> dict:
    MODEL_DIR.mkdir(exist_ok=True)
    prov = sorted({c.provenance for c in train_cases} | set(cfg.get("extra_provenance", []))
                  | set((parent or {}).get("provenance", [])))
    lic = sorted({c.commercial_use for c in train_cases} | ({"allowed"} if cfg.get("extra_provenance") == ["synthetic"] else set()))
    if cfg.get("extra_provenance") and sampler_manifest is None:
        lic = sorted(set(lic) | {"undocumented_sampler_source"})       # review ARC-02: sampler data must be listed
    tag = "commercial_eligible" if lic == ["allowed"] else "research_only"
    if parent and parent.get("licence_tag") != "commercial_eligible":
        tag = "research_only"
    manifest = [{"case_id": c.case_id, "provenance": c.provenance, "commercial_use": c.commercial_use,
                 "image_sha256": hashlib.sha256(np.ascontiguousarray(c.image).tobytes()).hexdigest()[:16]}
                for c in train_cases]
    ck = {"state_dict": model.state_dict(), "hparams": _plain(model.hparams), "cfg": _plain(cfg), "name": name,
          "provenance": prov, "licence_tag": tag, "train_manifest": _plain(manifest), "history": _plain(hist),
          "parent_model": _plain(parent), "sampler_manifest": _plain(sampler_manifest),
          "created": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
          "env": {"torch": str(torch.__version__), "python": platform.python_version(), "numpy": str(np.__version__),
                  **code_version()},
          "n_params": n_params(model), "train_seconds": round(seconds, 1)}
    p = MODEL_DIR / f"{name}.pt"
    torch.save(ck, p)
    sha = hashlib.sha256(p.read_bytes()).hexdigest()
    card = {k: v for k, v in ck.items() if k not in ("state_dict",)}
    card["sha256"] = sha
    card["path"] = str(p.relative_to(MODEL_DIR.parent))
    card["warning"] = ("SYNTHETIC-TRAINED — research prototype, not for study decisions"
                       if prov == ["synthetic"] else "Research prototype — not validated")
    (MODEL_DIR / f"{name}.card.json").write_text(json.dumps(card, indent=1, default=str))
    update_registry(name, {"sha256": sha, "created": ck["created"], "provenance": prov, "licence_tag": tag,
                           "n_train": len(train_cases), "cfg": _plain(cfg),
                           "parent": (parent or {}).get("name")})
    return card


def update_registry(name: str, entry: dict | None = None, merge: dict | None = None) -> None:
    """Locked, atomic read-modify-write of models/registry.json (review ARC-03: concurrent writers lost
    entries). ``entry`` replaces the model's record; ``merge`` updates fields of an existing record."""
    import fcntl
    import tempfile
    reg = MODEL_DIR / "registry.json"
    lock = MODEL_DIR / ".registry.lock"
    with open(lock, "a") as lf:
        fcntl.flock(lf, fcntl.LOCK_EX)
        try:
            R = json.loads(reg.read_text()) if reg.exists() else {}
            if entry is not None:
                R[name] = entry
            if merge is not None:
                R.setdefault(name, {}).update(merge)
            fd, tmp = tempfile.mkstemp(dir=MODEL_DIR, prefix=".registry.", suffix=".tmp")
            with os.fdopen(fd, "w") as f:
                f.write(json.dumps(R, indent=1, default=str))
                f.flush()
                os.fsync(f.fileno())
            os.replace(tmp, reg)
        finally:
            fcntl.flock(lf, fcntl.LOCK_UN)


def _plain(o):
    """JSON round-trip so checkpoints contain only types accepted by torch.load(weights_only=True)."""
    return json.loads(json.dumps(o, default=lambda x: x.item() if hasattr(x, "item") else str(x)))


MODEL_NAME_RE = r"^[A-Za-z0-9_\-]{1,64}$"


def load_model(name, verify_registry: bool = True) -> tuple[UNet3D, dict]:
    """Load a registered model by NAME only (no arbitrary paths). The file's SHA-256 is checked
    against models/registry.json BEFORE deserialisation, and deserialisation uses
    torch.load(weights_only=True) (tensors and plain containers only — no pickled code)."""
    import re
    if not re.fullmatch(MODEL_NAME_RE, str(name)):
        raise ValueError("Invalid model name")
    p = MODEL_DIR / f"{name}.pt"
    if not p.is_file():
        raise FileNotFoundError(f"Model {name} not found")
    data = p.read_bytes()
    sha = hashlib.sha256(data).hexdigest()
    if verify_registry:
        reg = json.loads((MODEL_DIR / "registry.json").read_text()) if (MODEL_DIR / "registry.json").exists() else {}
        if name not in reg or reg[name]["sha256"] != sha:
            raise RuntimeError(f"Model {name}: file hash does not match registry (locked model version changed)")
    import io as _io
    ck = torch.load(_io.BytesIO(data), map_location="cpu", weights_only=True)
    m = UNet3D(**ck["hparams"])
    m.load_state_dict(ck["state_dict"])
    m.eval()
    ck["sha256"] = sha
    return m, ck


def verify_model_lock(name, expected_sha256) -> bool:
    p = MODEL_DIR / f"{name}.pt"
    return hashlib.sha256(p.read_bytes()).hexdigest() == expected_sha256


# ----------------------------------------------------------------------------- inference
def _gauss_window(ps, sigma_scale=0.125):
    g = [np.exp(-0.5 * ((np.arange(p) - (p - 1) / 2) / (p * sigma_scale)) ** 2) for p in ps]
    w = g[0][:, None, None] * g[1][None, :, None] * g[2][None, None, :]
    return (w / w.max()).astype(np.float32) + 1e-3


@torch.no_grad()
def predict_proba(model, case: Case, cfg: dict, tta=False, patch=None, overlap=0.5,
                  mc_dropout: int = 0) -> np.ndarray:
    """Sliding-window softmax probabilities (C, Z, Y, X) with Gaussian blending.
    ``tta`` averages over 4 flip combinations; ``mc_dropout`` > 0 enables dropout sampling."""
    x = build_input(case, cfg)
    ps = tuple(patch or cfg.get("infer_patch", cfg.get("patch", (48, 48, 48))))
    ps = tuple(min(p, s) for p, s in zip(ps, x.shape[1:]))
    C = model.hparams["n_classes"]
    model.eval()
    if mc_dropout:
        for m in model.modules():
            if isinstance(m, torch.nn.Dropout3d):
                m.train()
    out = np.zeros((C,) + x.shape[1:], np.float32)
    wsum = np.zeros(x.shape[1:], np.float32)
    w = _gauss_window(ps)
    steps = [max(1, int(p * (1 - overlap))) for p in ps]
    starts = [sorted(set(list(range(0, max(s - p, 0) + 1, st)) + [max(s - p, 0)]))
              for s, p, st in zip(x.shape[1:], ps, steps)]
    flips = [(), (3,), (4,), (3, 4)] if tta else [()]
    n_s = max(1, mc_dropout)
    for z0 in starts[0]:
        for y0 in starts[1]:
            for x0 in starts[2]:
                sl = (slice(z0, z0 + ps[0]), slice(y0, y0 + ps[1]), slice(x0, x0 + ps[2]))
                xb = torch.from_numpy(np.ascontiguousarray(x[(slice(None),) + sl]))[None]
                acc = 0
                for f in flips:
                    for _ in range(n_s):
                        xi = torch.flip(xb, f) if f else xb
                        p = torch.softmax(model(xi), 1)
                        p = torch.flip(p, f) if f else p
                        acc = acc + p
                acc = (acc / (len(flips) * n_s))[0].numpy()
                out[(slice(None),) + sl] += acc * w
                wsum[sl] += w
    return out / wsum[None]


def code_version() -> dict:
    """Git commit (+dirty flag) and a hash of the osteoquant package sources (review ARC-05)."""
    import subprocess
    root = Path(__file__).resolve().parents[2]
    h = hashlib.sha256()
    for f in sorted((root / "osteoquant").rglob("*.py")):
        h.update(f.relative_to(root).as_posix().encode())
        h.update(f.read_bytes())
    out = {"osteoquant_source_sha256": h.hexdigest()}
    try:
        out["git_commit"] = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True,
                                           text=True, timeout=5).stdout.strip() or None
        out["git_dirty"] = bool(subprocess.run(["git", "-C", str(root), "status", "--porcelain", "osteoquant"],
                                               capture_output=True, text=True, timeout=5).stdout.strip())
    except Exception:
        out["git_commit"] = None
    return out
