def write_sbom(inv: dict, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = [("OsteoQuant Desktop", _app_version(), "proprietary (no licence chosen yet)", "application", "-")]
    rows += [(e["name"], e["version"], e.get("license") or "see licence file", "python", "bundled")
             for e in inv["python_distributions"]]
    rows.append(("Python runtime", inv["python"], "PSF-2.0", "runtime", "bundled"))
    rows += [(pkg.split(":")[0], i["version"], "see licenses/" + (i.get("licence_file") or "?"), "system-library",
              "bundled: " + " ".join(sorted(i["files"]))) for pkg, i in sorted(inv["system_packages"].items())]
    rows += [(q["component"], inv["qt_version"], q["license"], "compiled-into-Qt", "bundled") for q in inv["qt_third_party"]]
    with open(out_dir / "SBOM.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["component", "version", "license", "type", "use"])
        w.writerows(rows)
    comps = []
    for e in inv["python_distributions"]:
        comps.append({"type": "library", "name": e["name"], "version": e["version"],
                      "purl": f"pkg:pypi/{e['name'].lower()}@{e['version']}",
                      "licenses": [{"license": {"name": e.get("license") or "see licence file"}}]})
    comps.append({"type": "platform", "name": "python", "version": inv["python"],
                  "purl": f"pkg:generic/python@{inv['python']}", "licenses": [{"license": {"id": "PSF-2.0"}}]})
    for pkg, i in sorted(inv["system_packages"].items()):
        name = pkg.split(":")[0]
        comps.append({"type": "library", "name": name, "version": i["version"],
                      "purl": f"pkg:deb/{_distro_id()}/{name}@{i['version']}?arch=amd64",
                      "licenses": [{"license": {"name": "see " + (i.get("licence_file") or "?")}}]})
    doc = {"bomFormat": "CycloneDX", "specVersion": "1.5", "version": 1,
           "metadata": {"timestamp": inv["generated"], "component": {"type": "application", "name": "osteoquant-desktop",
                                                                      "version": _app_version()},
                        "properties": [{"name": "build-platform", "value": inv["platform"]}]},
           "components": comps}
    (out_dir / "sbom.cdx.json").write_text(json.dumps(doc, indent=1))


def _distro_id() -> str:
    try:
        m = re.search(r"^ID=(\w+)", Path("/etc/os-release").read_text(), re.M)
        return m.group(1) if m else "debian"
    except OSError:
        return "debian"


def _app_version() -> str:
    m = re.search(r'__version__\s*=\s*"([^"]+)"', (ROOT / "osteoquant" / "__init__.py").read_text())
    return m.group(1) if m else "unknown"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("root", nargs="?", default=str(PKG / "dist" / "OsteoQuant"))
    ap.add_argument("--sbom-dir", default=None, help="also write SBOM.csv and sbom.cdx.json here")
    ap.add_argument("--no-write", action="store_true", help="report only; change nothing")
    a = ap.parse_args(argv)
    inv = inventory(Path(a.root), write=not a.no_write)
    if a.sbom_dir and not a.no_write:
        write_sbom(inv, Path(a.sbom_dir))
    n_sys = sum(len(i["files"]) for i in inv["system_packages"].values())
    print(f"libraries: {len(inv['libraries'])}; system libraries: {n_sys} from {len(inv['system_packages'])} packages; "
          f"python distributions: {len(inv['python_distributions'])}")
    if inv["distributions_without_licence_file"]:
        print("distributions with no licence file:", ", ".join(inv["distributions_without_licence_file"]))
    if inv["unmapped"]:
        print(f"INVENTORY FAILED: {len(inv['unmapped'])} libraries without a mapped licence:")
        for u in inv["unmapped"]:
            print("   ", u)
        return 1
    print("INVENTORY PASSED: every bundled library is mapped to a licence source.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
