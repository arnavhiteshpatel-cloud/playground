    ("SHA-3 / Keccak and SHA-1 / RFC 6234 code (Qt Core)", "CC0-1.0 / BSD-3-Clause"),
    ("Easing equations by Robert Penner (Qt Core)", "BSD-3-Clause"),
    ("Unicode Character Database / CLDR data (Qt Core)", "Unicode-3.0"),
    ("HarfBuzz-NG (Qt Gui)", "MIT-Modern-Variant"),
    ("FreeType 2 (Qt Gui)", "FTL OR GPL-2.0-only (used under the FTL)"),
    ("libpng (Qt Gui)", "libpng-2.0"),
    ("libjpeg-turbo (Qt Gui)", "IJG AND BSD-3-Clause AND Zlib"),
    ("md4c (Qt Gui markdown)", "MIT"),
    ("OpenGL / Vulkan / EGL headers (Khronos)", "MIT / Apache-2.0"),
    ("xcb-util family and xkbcommon headers (Qt XcbQpa)", "MIT / X11"),
    ("Wayland protocol files (Qt WaylandClient)", "MIT"),
    ("PDFium and its third-party code (Qt Pdf)", "BSD-3-Clause AND Apache-2.0 AND others (see Qt Pdf attributions)"),
