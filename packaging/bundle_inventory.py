#!/usr/bin/env python
"""Bundle inventory, system-library notices and SBOM for a built OsteoQuant Desktop folder.

    python packaging/bundle_inventory.py [packaging/dist/OsteoQuant] [--sbom-dir docs/security] [--no-write]

Run by ``packaging/build.py`` after the Python-distribution licences are written (review C2-BIZ-08/-10, IP-03/-04).
It closes the gaps that the Python-distribution scan cannot see:

1. **Every shared library in the bundle is mapped to an owner and a licence source.**
   * libraries inside a wheel's package or ``<name>.libs`` folder -> that Python distribution (licence texts are
     copied by ``build.py`` into ``licenses/``; wheels that vendor libraries, e.g. Pillow, list them in their
     licence file);
   * ``libpython*`` -> the Python runtime: the PSF licence text from the build interpreter is copied to
     ``licenses/Python-PSF-LICENSE.txt``;
   * other top-level libraries copied from the build host (libgcrypt, libsystemd, libdbus-1, krb5/GSSAPI,
     OpenSSL 3, fontconfig, FreeType, HarfBuzz, ICU, xkbcommon, ...) -> the Debian package that owns the file
     (``dpkg -S``); its ``/usr/share/doc/<package>/copyright`` file, which carries the upstream licence texts
     (LGPL-2.1+ for libgcrypt/libsystemd, the Unicode licence for ICU, the FreeType Project Licence, ...), is
     copied to ``licenses/system/``.
   Any library that cannot be mapped is a FAILURE (exit status 1): it must not be distributed.
2. **Wheels whose licence files are in sub-folders** (pypdfium2: PDFium and its dependencies under
   ``dist-info/licenses/``) and distributions with no licence file (pyparsing) are completed.
3. **Qt's own third-party code** (compiled into the Qt libraries) is listed with its licences in
   ``THIRD_PARTY_NOTICES.txt``, with the exact Qt version and source location.
4. A machine-readable inventory (``licenses/BUNDLE_INVENTORY.json``) and the SBOM (``SBOM.csv`` and CycloneDX
   ``sbom.cdx.json`` with purls) are written. The SBOM describes the bundle that was actually built.

Linux only for the system-library mapping (dpkg). Windows and macOS builds have not been made; their inventory
must be produced on those builders before distribution.
"""
from __future__ import annotations

import argparse
import csv
import datetime as dt
import importlib.metadata as md
import json
import re
import shutil
import subprocess
import sys
import sysconfig
from pathlib import Path

PKG = Path(__file__).resolve().parent
ROOT = PKG.parent
LIB_RE = re.compile(r"\.(so(\.\d+)*|dylib|dll|pyd)$", re.I)
MARK = "\n# ---- generated by packaging/bundle_inventory.py ----\n"

