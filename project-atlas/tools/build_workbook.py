#!/usr/bin/env python3
"""Build the master opportunity workbook (10_deliverables/Atlas_Opportunity_Workbook.xlsx).

Live formulas: composite and evidence-adjusted scores recompute from the editable Weights sheet.
Run after tools/merge.py and tools/score.py.
"""
import csv, json, pathlib
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment
from openpyxl.utils import get_column_letter as L
from openpyxl.worksheet.table import Table, TableStyleInfo
from openpyxl.formatting.rule import ColorScaleRule

ROOT = pathlib.Path(__file__).resolve().parents[1]
DB, SCR, OUT = ROOT / "09_databases", ROOT / "03_screening", ROOT / "10_deliverables"
KEYS = ["fcf","roic","access","scale","resilience","entry","delegation","cash","feasibility","ai"]
W1 = [.18,.15,.12,.12,.10,.10,.08,.05,.05,.05]
LABELS = ["FCF & owner wealth","ROIC & capital efficiency","Customer access","Scalability","Resilience",
          "Competitive entry","Delegation","Cash conversion","Reg./practical feasibility","AI leverage"]
HDR = PatternFill("solid", fgColor="1F3864"); HF = Font(bold=True, color="FFFFFF")
INPUT = PatternFill("solid", fgColor="FFF2CC")


def jl(p):
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()] if p.exists() else []


def short(v, n=500):
    if v is None:
        return None
    if isinstance(v, (list, dict)):
        v = "; ".join(map(str, v)) if isinstance(v, list) else json.dumps(v, ensure_ascii=False)
    v = str(v)
    return v if len(v) <= n else v[:n - 1] + "…"


def header(ws, row, cols):
    for i, c in enumerate(cols, 1):
        cell = ws.cell(row=row, column=i, value=c); cell.fill = HDR; cell.font = HF
        cell.alignment = Alignment(wrap_text=True, vertical="top")


def main():
    opps = jl(DB / "opportunities.jsonl")
    srcs = jl(DB / "sources.jsonl")
    scores = {}
    if (SCR / "scores.csv").exists():
        with (SCR / "scores.csv").open(encoding="utf-8") as f:
            for r in csv.DictReader(f):
                scores[r["id"]] = r
    wb = Workbook()
    ws = wb.active; ws.title = "README"
    txt = ["Project Atlas — Master Opportunity Workbook", "",
           f"{len(opps)} opportunity records from 18 discovery workstreams; {len(srcs)} source records.",
           "Sheets: Weights (editable), Opportunities (all records; composite scores are LIVE formulas from Weights),",
           "Scores_Detail (original author scores, blind re-scores, current scores), Rankings (alternative profiles, from tools/score.py),",
           "Sources (evidence database), Gates (FAIL/WARN flags and rejection reasons).",
           "", "Score scale 1–10 per criterion (see 00_governance/SCORING_FRAMEWORK.md for anchors).",
           "Evidence-adjusted score = 5 + (raw − 5) × k, with k by evidence level (Weights sheet). Weak evidence shrinks toward 5.",
           "Change the yellow weights to see the ranking change; sort/filter the Opportunities table by any column.",
           "Numbers marked by evidence level E are assumptions/estimates, not facts. Year-3 profit ranges are for a capable new entrant.",
           "Generated by tools/build_workbook.py — rebuild after any data change."]
    for i, t in enumerate(txt, 1):
        ws.cell(row=i, column=1, value=t)
    ws["A1"].font = Font(bold=True, size=14); ws.column_dimensions["A"].width = 140
    # Weights
    ww = wb.create_sheet("Weights")
    ww["A1"] = "Criterion weights (editable)"; ww["A1"].font = Font(bold=True, size=13)
    for j, (k, lab, w) in enumerate(zip(KEYS, LABELS, W1)):
        ww.cell(row=2, column=2 + j, value=k).font = Font(bold=True)
        ww.cell(row=3, column=2 + j, value=lab)
        c = ww.cell(row=4, column=2 + j, value=w); c.fill = INPUT; c.number_format = "0%"
    ww["A2"] = "key"; ww["A3"] = "criterion"; ww["A4"] = "weight"; ww["A5"] = "sum"; ww["B5"] = "=SUM(B4:K4)"
    ww["A7"] = "Evidence shrinkage k"; ww["A7"].font = Font(bold=True)
    for i, (lvl, k) in enumerate([("A", 1.0), ("B", .95), ("C", .85), ("D", .70), ("E", .55)]):
        ww.cell(row=8 + i, column=1, value=lvl); c = ww.cell(row=8 + i, column=2, value=k); c.fill = INPUT
    # Opportunities
    wo = wb.create_sheet("Opportunities")
    cols = (["ID", "Title", "Workstream", "Industry", "Subindustry", "Mechanisms", "Evidence (current)", "Max stage",
             "Gate FAIL", "Gate WARN", "Duplicate of"] + [f"S_{k}" for k in KEYS] +
            ["Composite (live)", "Evidence-adjusted (live)", "Rank (adj, live)", "Raw v1 (static)", "Weight-sens P(top25)",
             "Launch capital low $", "Launch capital high $", "Validation cost $", "Months to first revenue",
             "Yr-3 op profit low $", "Yr-3 op profit high $", "Milestone ceiling", "Gross margin low %", "Gross margin high %",
             "Product / service", "Target customer", "Purchase motivation", "Revenue mechanism", "Typical transaction",
             "Entry strategy (wedge)", "Customer accessibility", "Supplier accessibility", "Competitive intensity",
             "Licenses / regulation", "Working capital", "Sales cycle", "Repeat purchase", "Acquisition channels",
             "Representative operators", "Spending evidence", "Failure modes", "Critical assumptions", "Unanswered questions",
             "Latest verdict", "Source IDs"])
    header(wo, 1, cols)
    n = len(opps)
    sc0 = cols.index("S_fcf") + 1
    for i, o in enumerate(opps):
        r = 2 + i
        cs = o.get("current_scores") or o.get("original_scores") or {}
        srow = scores.get(o["id"], {})
        vals = [o["id"], o.get("title"), o.get("workstream"), o.get("industry"), o.get("subindustry"),
                short(o.get("mechanisms")), o.get("current_evidence_confidence") or o.get("evidence_confidence"),
                o.get("max_stage", "A"), srow.get("gate_fail") or None, srow.get("gate_warn") or None, o.get("duplicate_of")]
        vals += [cs.get(k) for k in KEYS]
        first, last = L(sc0), L(sc0 + 9)
        ev = L(cols.index("Evidence (current)") + 1)
        comp = L(sc0 + 10); adj = L(sc0 + 11)
        vals += [f"=SUMPRODUCT({first}{r}:{last}{r},Weights!$B$4:$K$4)/Weights!$B$5",
                 f"=5+({comp}{r}-5)*IFERROR(VLOOKUP({ev}{r},Weights!$A$8:$B$12,2,FALSE),0.55)",
                 f"=IF(OR({L(cols.index('Gate FAIL')+1)}{r}<>\"\",{L(cols.index('Duplicate of')+1)}{r}<>\"\"),\"\",COUNTIFS(${adj}$2:${adj}${n+1},\">\"&{adj}{r},${L(cols.index('Gate FAIL')+1)}$2:${L(cols.index('Gate FAIL')+1)}${n+1},\"\",${L(cols.index('Duplicate of')+1)}$2:${L(cols.index('Duplicate of')+1)}${n+1},\"\")+1)",
                 float(srow["raw_score"]) if srow.get("raw_score") else None,
                 float(srow["p_top25_weight_sens"]) if srow.get("p_top25_weight_sens") else None]
        vals += [o.get("current_launch_capital_usd_low"), o.get("current_launch_capital_usd_high"),
                 o.get("current_validation_cost_usd"), o.get("time_to_first_revenue_months"),
                 o.get("current_yr3_operating_profit_usd_low"), o.get("current_yr3_operating_profit_usd_high"),
                 o.get("current_plausible_milestone_ceiling"), o.get("gross_margin_pct_low"), o.get("gross_margin_pct_high")]
        vals += [short(o.get(k)) for k in ["product_service", "target_customer", "purchase_motivation", "revenue_mechanism",
                 "typical_transaction_value", "entry_strategy", "customer_accessibility", "supplier_accessibility",
                 "competitive_intensity", "licenses", "working_capital_note", "sales_cycle", "repeat_purchase",
                 "acquisition_channels", "representative_operators", "spending_evidence", "failure_modes",
                 "critical_assumptions", "unanswered_questions", "latest_verdict", "source_ids"]]
        for j, v in enumerate(vals, 1):
            c = wo.cell(row=r, column=j, value=v)
            if j in (sc0 + 10, sc0 + 11, sc0 + 13):
                c.number_format = "0.00"
    if n:
        ref = f"A1:{L(len(cols))}{n+1}"
        t = Table(displayName="Opportunities", ref=ref)
        t.tableStyleInfo = TableStyleInfo(name="TableStyleLight9", showRowStripes=True)
        wo.add_table(t)
        wo.conditional_formatting.add(f"{L(sc0)}2:{L(sc0+9)}{n+1}",
            ColorScaleRule(start_type="num", start_value=1, start_color="F8696B", mid_type="num", mid_value=5,
                           mid_color="FFEB84", end_type="num", end_value=10, end_color="63BE7B"))
    wo.freeze_panes = "C2"
    for j, wdt in enumerate([10, 44, 8, 22, 22, 26, 8, 6, 12, 12, 10] + [5] * 10 + [9, 9, 7, 8, 8] + [11] * 9 + [50] * 21, 1):
        wo.column_dimensions[L(j)].width = wdt
    # Scores detail
    wd = wb.create_sheet("Scores_Detail")
    hcols = ["ID", "Title", "Score basis"] + [f"orig_{k}" for k in KEYS] + [f"blind_{k}" for k in KEYS] + \
            [f"cur_{k}" for k in KEYS] + ["Blind rationale"]
    header(wd, 1, hcols)
    for i, o in enumerate(opps):
        os_, bs, cs = o.get("original_scores") or {}, o.get("blind_scores") or {}, o.get("current_scores") or {}
        row = [o["id"], o.get("title"), o.get("current_score_basis")] + [os_.get(k) for k in KEYS] + \
              [bs.get(k) for k in KEYS] + [cs.get(k) for k in KEYS] + [short(o.get("blind_rationale"), 800)]
        for j, v in enumerate(row, 1):
            wd.cell(row=2 + i, column=j, value=v)
    wd.freeze_panes = "C2"; wd.column_dimensions["B"].width = 44
    # Rankings (static from score.py)
    wr = wb.create_sheet("Rankings")
    if scores:
        profiles = [c[2:] for c in next(iter(scores.values())).keys() if c.startswith("p_") and not c.startswith("p_top")]
        header(wr, 1, ["Rank"] + sum([[f"{p} ID", f"{p} title", f"{p} score"] for p in profiles], []))
        elig = [r for r in scores.values() if not r.get("gate_fail") and not r.get("duplicate_of")]
        for j, p in enumerate(profiles):
            ranked = sorted(elig, key=lambda r: -float(r[f"p_{p}"]))[:50]
            for i, r in enumerate(ranked):
                wr.cell(row=2 + i, column=1, value=i + 1)
                wr.cell(row=2 + i, column=2 + 3 * j, value=r["id"])
                wr.cell(row=2 + i, column=3 + 3 * j, value=r["title"])
                wr.cell(row=2 + i, column=4 + 3 * j, value=round(float(r[f"p_{p}"]), 2))
        wr.freeze_panes = "B2"
    # Sources
    wsr = wb.create_sheet("Sources")
    scols = ["source_id", "evidence_level", "organization", "title", "url", "publication_date", "access_date", "claim",
             "excerpt", "limitations", "opportunity_ids"]
    header(wsr, 1, scols)
    for i, s in enumerate(srcs):
        for j, k in enumerate(scols, 1):
            wsr.cell(row=2 + i, column=j, value=short(s.get(k), 600))
    if srcs:
        t = Table(displayName="Sources", ref=f"A1:{L(len(scols))}{len(srcs)+1}")
        t.tableStyleInfo = TableStyleInfo(name="TableStyleLight1", showRowStripes=True)
        wsr.add_table(t)
    wsr.freeze_panes = "B2"
    # Gates
    wg = wb.create_sheet("Gates")
    header(wg, 1, ["ID", "Title", "Gate FAIL", "Gate WARN", "Duplicate of", "Dedupe note", "Verdict"])
    for i, o in enumerate(opps):
        srow = scores.get(o["id"], {})
        for j, v in enumerate([o["id"], o.get("title"), srow.get("gate_fail"), srow.get("gate_warn"),
                               o.get("duplicate_of"), o.get("dedupe_note"), short(o.get("latest_verdict"), 400)], 1):
            wg.cell(row=2 + i, column=j, value=v)
    OUT.mkdir(exist_ok=True)
    p = OUT / "Atlas_Opportunity_Workbook.xlsx"
    wb.save(p)
    print(f"wrote {p} ({n} opportunities, {len(srcs)} sources)")


if __name__ == "__main__":
    main()
