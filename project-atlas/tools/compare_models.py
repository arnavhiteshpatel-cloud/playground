#!/usr/bin/env python3
"""Compare all built financial models (08_financial_models/*_results.json).

Writes 08_financial_models/MODEL_COMPARISON.md and 10_deliverables/Atlas_Model_Comparison.xlsx with:
 - scenario table (Y1/Y3/Y5 op profit, peak funding, breakeven, payback, milestones, 10-yr deployable, EV)
 - stress-test survival matrix (base case under each stress; flags tests where Y3 op < 0 or peak funding > $100k)
 - top sensitivity driver per model
Usage: python3 tools/compare_models.py [ID ...]   (default: all except TEMPLATE)
"""
import json, pathlib, sys
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill

ROOT = pathlib.Path(__file__).resolve().parents[1]
FM = ROOT / "08_financial_models"
HDR = PatternFill("solid", fgColor="1F3864"); HF = Font(bold=True, color="FFFFFF")


def k(v):
    if v is None:
        return "–"
    if isinstance(v, str):
        return v
    if abs(v) >= 1e6:
        return f"${v/1e6:.2f}M"
    if abs(v) >= 1e3:
        return f"${v/1e3:.0f}k"
    return f"${v:.0f}"


def mo(v):
    return "never" if not v else f"m{int(v)}"


def main():
    ids = sys.argv[1:] or sorted(p.name.replace("_results.json", "") for p in FM.glob("*_results.json")
                                 if not p.name.startswith("TEMPLATE"))
    res = {i: json.loads((FM / f"{i}_results.json").read_text()) for i in ids if (FM / f"{i}_results.json").exists()}
    md = ["# Financial Model Comparison (auto-generated by tools/compare_models.py)\n",
          "All figures from each model's Python mirror (identical to the XLSX formulas; see verify_fin_model.py). "
          "Operating profit is EBITDA-basis before owner compensation. Peak funding = maximum cumulative cash deficit "
          "after owner draw (the capital actually at risk). 'Deployable' = cumulative surplus after reinvestment and "
          "reserves (10-yr). These are model outputs from evidenced-but-unvalidated drivers — not forecasts.\n"]
    md.append("## Scenario summary\n")
    md.append("| ID | Name | Scen | Y1 op | Y3 op | Y5 op | Peak funding | Breakeven | Payback | ≥$10k/mo | ≥$25k/mo | 10-yr deployable | Y10 EV |")
    md.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    rows = []
    for i, r in res.items():
        for s in ("conservative", "base", "optimistic"):
            S = r["scenarios"][s]
            rows.append([i, r["name"][:40], s[:4], S["y1_op"], S["y3_op"], S["y5_op"], S["peak_funding_need"],
                         S["breakeven_month"], S["payback_month"], S["first_month_op_10k"], S["first_month_op_25k"],
                         S["lt_y10_cum_deployable"], S["lt_y10_ev"]])
            md.append(f"| {i} | {r['name'][:40]} | {s[:4]} | {k(S['y1_op'])} | {k(S['y3_op'])} | {k(S['y5_op'])} | "
                      f"{k(S['peak_funding_need'])} | {mo(S['breakeven_month'])} | {mo(S['payback_month'])} | "
                      f"{mo(S['first_month_op_10k'])} | {mo(S['first_month_op_25k'])} | {k(S['lt_y10_cum_deployable'])} | {k(S['lt_y10_ev'])} |")
    md.append("\n## Stress survival (base case)\n")
    md.append("Cell = Y3 operating profit under the stress; ⚠ = Y3 op < 0 or peak funding > $100k.\n")
    tests = [t["test"] for t in next(iter(res.values()))["stress"]] if res else []
    md.append("| Stress | " + " | ".join(res) + " |")
    md.append("|---|" + "---|" * len(res))
    for ti, t in enumerate(tests):
        cells = []
        for i, r in res.items():
            st = r["stress"][ti]
            flag = " ⚠" if st["y3_op"] < 0 or st["peak_funding_need"] > 100000 else ""
            cells.append(k(st["y3_op"]) + flag)
        md.append(f"| {t} | " + " | ".join(cells) + " |")
    md.append("\n## Most sensitive driver (base case, ±25%)\n")
    md.append("| ID | Driver | Y3 op @×0.75 | Y3 op @×1.25 |\n|---|---|---|---|")
    for i, r in res.items():
        t = r["tornado"][0]
        md.append(f"| {i} | {t['driver']} | {k(t['y3_op_low'])} | {k(t['y3_op_high'])} |")
    (FM / "MODEL_COMPARISON.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    wb = Workbook(); ws = wb.active; ws.title = "Scenarios"
    cols = ["ID", "Name", "Scenario", "Y1 op", "Y3 op", "Y5 op", "Peak funding", "Breakeven month", "Payback month",
            "First month ≥$10k", "First month ≥$25k", "10-yr deployable", "Y10 EV"]
    for j, c in enumerate(cols, 1):
        cell = ws.cell(row=1, column=j, value=c); cell.fill = HDR; cell.font = HF
    for r_i, row in enumerate(rows, 2):
        for j, v in enumerate(row, 1):
            c = ws.cell(row=r_i, column=j, value=round(v) if isinstance(v, float) else v)
            if j >= 4 and j not in (8, 9, 10, 11):
                c.number_format = "#,##0"
    ws.freeze_panes = "D2"; ws.column_dimensions["B"].width = 42
    ws2 = wb.create_sheet("Stress")
    ws2.cell(row=1, column=1, value="Stress test (Y3 op profit, base case)").font = Font(bold=True)
    for j, i in enumerate(res, 2):
        ws2.cell(row=1, column=j, value=i).font = Font(bold=True)
    for ti, t in enumerate(tests, 2):
        ws2.cell(row=ti, column=1, value=t)
        for j, (i, r) in enumerate(res.items(), 2):
            ws2.cell(row=ti, column=j, value=round(r["stress"][ti - 2]["y3_op"])).number_format = "#,##0"
    ws2.column_dimensions["A"].width = 60
    out = ROOT / "10_deliverables" / "Atlas_Model_Comparison.xlsx"; out.parent.mkdir(exist_ok=True)
    wb.save(out)
    print(f"compared {len(res)} models -> {FM/'MODEL_COMPARISON.md'}, {out}")


if __name__ == "__main__":
    main()
