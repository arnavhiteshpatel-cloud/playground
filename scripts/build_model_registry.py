"""Regenerate MODEL_REGISTRY.md from models/registry.json and model cards."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REG = ROOT / "models" / "registry.json"
OUT = ROOT / "MODEL_REGISTRY.md"

HEADER = """# Model Registry

Generated by `scripts/build_model_registry.py` from `models/registry.json` (weights are git-ignored; every entry
records the SHA-256 that `osteoquant.ml.train.load_model` verifies before loading).
**Release status** values: `research` (experiments only), `candidate` (passed benchmark gates, not released),
`released` (none yet). No model in this registry is validated on real three-class graft data.

| Name | Task / classes | Provenance of training data | Licence tag | n train | Iters | Seed | Release status | SHA-256 (first 12) |
|---|---|---|---|---|---|---|---|---|
"""


def main() -> None:
    reg = json.loads(REG.read_text()) if REG.exists() else {}
    rows = []
    for name, e in sorted(reg.items()):
        cfg = e.get("cfg", {})
        ncls = cfg.get("n_classes", 4)
        task = "3-class + background" if ncls == 4 else f"{ncls}-class"
        rows.append(f"| `{name}` | {task} | {', '.join(e.get('provenance', []))} | {e.get('licence_tag', '?')} | "
                    f"{e.get('n_train', '?')} | {cfg.get('iters', '?')} | {cfg.get('seed', '?')} | "
                    f"{e.get('release_status', 'research')} | `{e.get('sha256', '')[:12]}` |")
    OUT.write_text(HEADER + "\n".join(rows) + "\n")
    print(f"{len(rows)} models -> {OUT}")


if __name__ == "__main__":
    main()
